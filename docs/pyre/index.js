// Pyre — a small, typed GPU language with Python-style syntax.
// One source file compiles to GLSL ES 3.00 (WebGL2), WGSL (WebGPU) and
// JavaScript (CPU, for Node.js, tests and machines without a GPU).
import { PyreError } from './errors.js';
import { tokenize } from './lexer.js';
import { parse as parseSource } from './parser.js';
import { check } from './checker.js';
import { genGLSL, GLSL_VERTEX } from './gen-glsl.js';
import { genWGSL, uniformLayout } from './gen-wgsl.js';
import { genJS } from './gen-js.js';
import { runtime } from './runtime.js';
import { STDLIB } from './stdlib.js';

export const VERSION = '1.0.0';
export const TARGETS = ['glsl', 'wgsl', 'js'];
export { PyreError, GLSL_VERTEX, runtime };

const DEFAULT_LOOP_LIMIT = 50_000_000;

function withSource(fn, source, filename) {
  try {
    return fn();
  } catch (err) {
    if (err instanceof PyreError) {
      err.source = source;
      err.filename = filename || '<input>';
    }
    throw err;
  }
}

export function parse(source, { filename } = {}) {
  return withSource(() => parseSource(source), source, filename);
}

/** Parse + type-check a program (with the standard library linked in). */
export function analyze(source, { filename } = {}) {
  return withSource(() => {
    const prog = parseSource(source);
    const std = parseSource(STDLIB);
    const own = new Set(prog.functions.map((f) => f.name));
    for (const f of std.functions) {
      if (!own.has(f.name)) { f.std = true; prog.functions.push(f); }
    }
    const names = new Set();
    for (const t of tokenize(source)) if (t.type === 'IDENT') names.add(t.value);
    for (const t of tokenize(STDLIB)) if (t.type === 'IDENT') names.add(t.value);
    return check(prog, names);
  }, source, filename);
}

function describe(info) {
  return {
    entry: info.fragment ? 'fragment' : info.kernel ? 'kernel' : null,
    fragmentInputs: info.fragment ? info.fragment.params.map((p) => p.name) : [],
    workgroupSize: info.kernel ? info.kernel.workgroupSize : null,
    uniforms: info.uniforms.map((u) => ({ name: u.name, type: u.type.name })),
    uniformLayout: uniformLayout(info.uniforms),
    buffers: info.buffers.map((b, i) => ({ name: b.name, elem: b.elem, binding: i + 1 })),
    functions: info.order.filter((f) => !f.std).map((f) => ({
      name: f.name,
      params: f.params.map((p, i) => ({ name: p.name, type: f.paramTypes[i] })),
      returns: f.retType,
      decorator: f.decorator ? f.decorator.name : null,
    })),
  };
}

/**
 * Compile Pyre source.
 * @param {string} source
 * @param {{target?: 'glsl'|'wgsl'|'js', filename?: string, version?: boolean}} [opts]
 * @returns {{target: string, code: string, meta: object}}
 */
export function compile(source, opts = {}) {
  const target = opts.target || 'glsl';
  if (!TARGETS.includes(target)) throw new Error(`unknown target '${target}' (use ${TARGETS.join(', ')})`);
  const info = analyze(source, opts);
  const code = withSource(() => {
    if (target === 'glsl') return genGLSL(info, opts);
    if (target === 'wgsl') return genWGSL(info);
    return jsModule(genJS(info));
  }, source, opts.filename);
  return { target, code, meta: describe(info) };
}

/** Compile to every target that applies; per-target errors are collected, not thrown. */
export function compileAll(source, opts = {}) {
  const info = analyze(source, opts);
  const result = { meta: describe(info), errors: {} };
  const tryGen = (name, fn) => {
    try {
      result[name] = withSource(fn, source, opts.filename);
    } catch (err) {
      if (!(err instanceof PyreError)) throw err;
      result.errors[name] = err.message;
    }
  };
  tryGen('glsl', () => genGLSL(info, opts));
  tryGen('wgsl', () => genWGSL(info));
  tryGen('js', () => genJS(info));
  return result;
}

/** Check a program and return diagnostics instead of throwing. */
export function diagnose(source, opts = {}) {
  try {
    const info = analyze(source, opts);
    return { ok: true, errors: [], meta: describe(info) };
  } catch (err) {
    if (err instanceof PyreError) return { ok: false, errors: [{ ...err.toJSON(), text: err.format() }] };
    throw err;
  }
}

function jsModule(body) {
  return `// generated by Pyre ${VERSION}\nimport { runtime as $R } from 'pyre-lang/runtime';\n\n`
    + `export function create($U = {}, $B = {}, $LIMIT = ${DEFAULT_LOOP_LIMIT}) {\n${body}}\n`;
}

const zeroOf = (t) => runtime.zero(t);

/**
 * Build a runnable CPU program.
 * @returns {{uniforms: object, buffers: object, fragment: Function|null, kernel: Function|null, run: Function, functions: object, meta: object}}
 */
export function createProgram(source, opts = {}) {
  const info = analyze(source, opts);
  const meta = describe(info);
  const body = genJS(info);
  const uniforms = {};
  for (const u of meta.uniforms) {
    uniforms[u.name] = opts.uniforms && u.name in opts.uniforms ? opts.uniforms[u.name] : zeroOf(u.type);
  }
  const buffers = {};
  for (const b of meta.buffers) {
    const given = opts.buffers && opts.buffers[b.name];
    const Ctor = b.elem === 'int' ? Int32Array : Float32Array;
    buffers[b.name] = given instanceof Ctor ? given : new Ctor(given || 0);
  }
  // eslint-disable-next-line no-new-func
  const factory = new Function('$R', '$U', '$B', '$LIMIT', body);
  const program = factory(runtime, uniforms, buffers, opts.loopLimit || DEFAULT_LOOP_LIMIT);
  return {
    meta,
    uniforms,
    buffers,
    fragment: program.fragment,
    kernel: program.kernel,
    functions: program.functions,
    run(count) {
      if (!program.kernel) throw new Error('this program has no @kernel function');
      const n = count ?? Math.max(0, ...Object.values(buffers).map((b) => b.length));
      for (let id = 0; id < n; id++) program.kernel(id);
      return buffers;
    },
  };
}

/** Run a @kernel on the CPU over `count` threads; returns the buffers. */
export function runKernel(source, { buffers, uniforms, count, loopLimit } = {}) {
  return createProgram(source, { buffers, uniforms, loopLimit }).run(count);
}

/** Render a @fragment shader on the CPU into RGBA8 pixels (top row first). */
export function renderFragment(source, { width = 256, height = 256, uniforms, loopLimit } = {}) {
  if (!(width > 0 && height > 0 && width * height <= 16_777_216)) throw new Error('image size must be positive and at most 16 megapixels');
  const prog = createProgram(source, { uniforms, loopLimit });
  if (!prog.fragment) throw new Error('this program has no @fragment function');
  const data = new Uint8ClampedArray(width * height * 4);
  const input = { uv: [0, 0], frag: [0, 0], normal: [0, 0, 1], position: [0, 0, 0] };
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const fx = x + 0.5;
      const fy = height - y - 0.5; // gl_FragCoord has its origin at the bottom
      input.uv = [fx / width, fy / height];
      input.frag = [fx, fy];
      input.position = [input.uv[0] * 2 - 1, input.uv[1] * 2 - 1, 0];
      const c = prog.fragment(input);
      const i = (y * width + x) * 4; // Uint8ClampedArray rounds to nearest, like unorm8
      data[i] = c[0] * 255;
      data[i + 1] = c[1] * 255;
      data[i + 2] = c[2] * 255;
      data[i + 3] = c[3] * 255;
    }
  }
  return { width, height, data };
}
