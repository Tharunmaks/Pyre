#!/usr/bin/env node
// Copies the compiler into docs/ so the playground works on GitHub Pages,
// and bundles the examples. Run after changing src/ or examples/.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { diagnose } from '../src/index.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dest = path.join(root, 'docs', 'pyre');
fs.rmSync(dest, { recursive: true, force: true });
fs.mkdirSync(dest, { recursive: true });
fs.cpSync(path.join(root, 'src'), dest, { recursive: true, filter: (f) => !f.endsWith('png.js') });
const files = fs.readdirSync(path.join(root, 'examples')).filter((f) => f.endsWith('.pyre'));
const entries = files.map((f) => {
  const src = fs.readFileSync(path.join(root, 'examples', f), 'utf8');
  return { name: f, src, entry: diagnose(src).meta.entry };
}).sort((a, b) => (a.entry === b.entry ? a.name.localeCompare(b.name) : a.entry === 'fragment' ? -1 : 1));
const order = ['raymarch.pyre', 'plasma.pyre'];
entries.sort((a, b) => (order.indexOf(b.name) - order.indexOf(a.name)));
fs.writeFileSync(path.join(root, 'docs', 'examples.js'),
  `// generated by scripts/build-docs.mjs\nexport const EXAMPLES = ${JSON.stringify(Object.fromEntries(entries.map((e) => [e.name, e.src])), null, 2)};\n`);
console.log(`docs: copied compiler, bundled ${entries.length} examples`);
