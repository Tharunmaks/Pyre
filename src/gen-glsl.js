// GLSL ES 3.00 (WebGL2) fragment shader generator.
import { fail } from './errors.js';
import { BUILTIN_CONSTS } from './types.js';

export const GLSL_VERTEX = `#version 300 es
in vec3 position;
in vec3 normal;
in vec2 uv;
uniform mat4 modelViewMatrix;
uniform mat4 projectionMatrix;
uniform mat3 normalMatrix;
out vec2 vUv;
out vec3 vNormal;
out vec3 vPosition;
void main() {
  vUv = uv;
  vNormal = normalize(normalMatrix * normal);
  vPosition = position;
  gl_Position = projectionMatrix * modelViewMatrix * vec4(position, 1.0);
}
`;

const INPUTS = { uv: 'vUv', frag: 'gl_FragCoord.xy', normal: 'normalize(vNormal)', position: 'vPosition' };
const VARYINGS = { uv: 'in vec2 vUv;', normal: 'in vec3 vNormal;', position: 'in vec3 vPosition;' };

export function fmtFloat(v) {
  if (Object.is(v, -0)) return '-0.0';
  const s = String(v);
  return /[.eE]/.test(s) ? s : s + '.0';
}

const ZERO = { bool: 'false', int: '0', float: '0.0' };
const zero = (t) => ZERO[t] || `${t}(0.0)`;

export function genGLSL(info, opts = {}) {
  if (!info.fragment) {
    if (info.kernel) fail('@kernel functions compile to WGSL or JS, not GLSL', info.kernel.pos);
    fail('GLSL output needs a @fragment function', null);
  }
  const out = [];
  if (opts.version !== false) out.push('#version 300 es');
  out.push('precision highp float;', 'precision highp int;', '// generated by Pyre');
  for (const p of info.fragment.params) if (VARYINGS[p.name]) out.push(VARYINGS[p.name]);
  for (const u of info.uniforms) out.push(`uniform ${u.type.name} ${u.out};`);
  out.push('out vec4 fragColor;');
  for (const [k, v] of Object.entries(BUILTIN_CONSTS)) out.push(`const float ${k} = ${fmtFloat(v)};`);
  for (const c of info.consts) out.push(`const ${c.type} ${c.out} = ${expr(c.init)};`);

  for (const f of info.reachable([info.fragment])) {
    const params = f.params.map((p, i) => `${f.paramTypes[i]} ${f.paramOut[i]}`).join(', ');
    out.push('', `${f.retType} ${f.out}(${params}) {`);
    block(f.body, 1);
    out.push('}');
  }
  const args = info.fragment.params.map((p) => INPUTS[p.name]).join(', ');
  out.push('', 'void main() {', `  fragColor = ${info.fragment.out}(${args});`, '}', '');
  return out.join('\n');

  function block(stmts, depth) {
    const ind = '  '.repeat(depth);
    for (const s of stmts) {
      switch (s.kind) {
        case 'let':
        case 'var':
          out.push(`${ind}${s.type} ${s.out} = ${s.init ? expr(s.init) : zero(s.type)};`);
          break;
        case 'assign':
          out.push(`${ind}${expr(s.target)} ${s.op} ${expr(s.value)};`);
          break;
        case 'expr':
          out.push(`${ind}${expr(s.expr)};`);
          break;
        case 'if':
          s.branches.forEach((b, i) => {
            out.push(`${ind}${i ? '} else if' : 'if'} (${expr(b.cond)}) {`);
            block(b.body, depth + 1);
          });
          if (s.otherwise) { out.push(`${ind}} else {`); block(s.otherwise, depth + 1); }
          out.push(`${ind}}`);
          break;
        case 'for': {
          const cmp = s.stepValue > 0 ? '<' : '>';
          out.push(`${ind}for (int ${s.out} = ${expr(s.start)}; ${s.out} ${cmp} ${expr(s.end)}; ${s.out} += ${s.stepValue}) {`);
          block(s.body, depth + 1);
          out.push(`${ind}}`);
          break;
        }
        case 'while':
          out.push(`${ind}while (${expr(s.cond)}) {`);
          block(s.body, depth + 1);
          out.push(`${ind}}`);
          break;
        case 'return':
          out.push(`${ind}return${s.value ? ' ' + expr(s.value) : ''};`);
          break;
        case 'break':
        case 'continue':
          out.push(`${ind}${s.kind};`);
          break;
        default:
          break;
      }
    }
  }

  function expr(e) {
    switch (e.kind) {
      case 'num': return e.isFloat ? fmtFloat(e.value) : String(e.value);
      case 'bool': return String(e.value);
      case 'ident':
        if (e.ref.kind === 'buffer') fail('buffers are not available in GLSL fragment shaders', e.pos);
        return e.ref.out;
      case 'unary': return e.op === 'not' ? `(!${expr(e.arg)})` : `(- ${expr(e.arg)})`;
      case 'binary': {
        const a = expr(e.left);
        const b = expr(e.right);
        if (e.op === '%') return e.type === 'int' ? `(${a} % ${b})` : `mod(${a}, ${b})`;
        if (e.op === '<<' || e.op === '>>') return `(${a} ${e.op} (${b} & 31))`;
        const op = e.op === 'and' ? '&&' : e.op === 'or' ? '||' : e.op;
        return `(${a} ${op} ${b})`;
      }
      case 'ternary': return `(${expr(e.cond)} ? ${expr(e.a)} : ${expr(e.b)})`;
      case 'member': return `${expr(e.object)}.${e.prop}`;
      case 'index':
        if (e.indexKind === 'buffer') fail('buffers are not available in GLSL fragment shaders', e.pos);
        return `${expr(e.object)}[${expr(e.index)}]`;
      case 'ucall': return `${e.fn.out}(${e.args.map(expr).join(', ')})`;
      case 'bcall': {
        const args = e.args.map(expr);
        if (e.callee === 'atan2') return `atan(${args.join(', ')})`;
        if (e.callee === 'saturate') return `clamp(${args[0]}, 0.0, 1.0)`;
        if (e.callee === 'mod' && e.generic === 'int') return `(${args[0]} % ${args[1]})`;
        return `${e.callee}(${args.join(', ')})`;
      }
      case 'construct': return `${e.ctor}(${e.args.map(expr).join(', ')})`;
      default: return fail('cannot generate GLSL for this expression', e.pos);
    }
  }
}

