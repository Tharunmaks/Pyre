// WGSL (WebGPU) generator for @fragment shaders and @kernel compute kernels.
import { fail } from './errors.js';
import { BUILTIN_CONSTS, dim, isMat, isVec } from './types.js';
import { fmtFloat } from './gen-glsl.js';

export function wgslType(t) {
  if (t === 'float') return 'f32';
  if (t === 'int') return 'i32';
  if (t === 'bool') return 'bool';
  if (isVec(t)) return `${t}<f32>`;
  if (isMat(t)) return `mat${dim(t)}x${dim(t)}<f32>`;
  return fail(`type ${t} has no WGSL equivalent`, null);
}

// std140-like layout rules for a WGSL uniform struct
const LAYOUT = { float: [4, 4], int: [4, 4], vec2: [8, 8], vec3: [12, 16], vec4: [16, 16], mat4: [64, 16] };
export function uniformLayout(uniforms) {
  let offset = 0;
  const fields = uniforms.map((u) => {
    const [size, align] = LAYOUT[u.type.name];
    offset = Math.ceil(offset / align) * align;
    const f = { name: u.name, type: u.type.name, offset, size };
    offset += size;
    return f;
  });
  return { fields, size: Math.max(16, Math.ceil(offset / 16) * 16) };
}

const BUILTIN_NAMES = { inversesqrt: 'inverseSqrt' };

export function genWGSL(info) {
  const roots = [info.fragment, info.kernel].filter(Boolean);
  if (!roots.length) fail('WGSL output needs a @fragment or @kernel function', null);
  const out = ['// generated by Pyre'];
  const modHelpers = new Set();

  for (const [k, v] of Object.entries(BUILTIN_CONSTS)) out.push(`const ${k}: f32 = ${fmtFloat(v)};`);
  if (info.uniforms.length) {
    out.push('struct PyreUniforms {');
    for (const u of info.uniforms) out.push(`  ${u.out}: ${wgslType(u.type.name)},`);
    out.push('}', '@group(0) @binding(0) var<uniform> pyre_u: PyreUniforms;');
  }
  info.buffers.forEach((b, i) => {
    out.push(`@group(0) @binding(${i + 1}) var<storage, read_write> ${b.out}: array<${wgslType(b.elem)}>;`);
  });
  for (const c of info.consts) out.push(`const ${c.out}: ${wgslType(c.type)} = ${expr(c.init)};`);

  const body = [];
  for (const f of info.reachable(roots)) {
    const params = f.params.map((p, i) => `${f.paramOut[i]}: ${wgslType(f.paramTypes[i])}`).join(', ');
    const ret = f.retType === 'void' ? '' : ` -> ${wgslType(f.retType)}`;
    body.push('', `fn ${f.out}(${params})${ret} {`);
    block(f.body, 1);
    body.push('}');
  }

  if (info.fragment) {
    body.push(
      '',
      'struct PyreFragmentIn {',
      '  @builtin(position) frag: vec4<f32>,',
      '  @location(0) uv: vec2<f32>,',
      '  @location(1) normal: vec3<f32>,',
      '  @location(2) position: vec3<f32>,',
      '}',
      '',
      '// full-screen triangle; pair with fs_main for 2D effects',
      '@vertex',
      'fn vs_fullscreen(@builtin(vertex_index) i: u32) -> PyreFragmentIn {',
      '  var o: PyreFragmentIn;',
      '  let p = vec2<f32>(f32((i << 1u) & 2u), f32(i & 2u));',
      '  o.frag = vec4<f32>(p * 2.0 - 1.0, 0.0, 1.0);',
      '  o.uv = p;',
      '  o.normal = vec3<f32>(0.0, 0.0, 1.0);',
      '  o.position = vec3<f32>(p * 2.0 - 1.0, 0.0);',
      '  return o;',
      '}',
      '',
      '@fragment',
      'fn fs_main(pyre_in: PyreFragmentIn) -> @location(0) vec4<f32> {',
    );
    const map = { uv: 'pyre_in.uv', frag: 'pyre_in.frag.xy', normal: 'normalize(pyre_in.normal)', position: 'pyre_in.position' };
    body.push(`  return ${info.fragment.out}(${info.fragment.params.map((p) => map[p.name]).join(', ')});`, '}');
  }
  if (info.kernel) {
    body.push(
      '',
      `@compute @workgroup_size(${info.kernel.workgroupSize})`,
      'fn cs_main(@builtin(global_invocation_id) pyre_gid: vec3<u32>) {',
      `  ${info.kernel.out}(i32(pyre_gid.x));`,
      '}',
    );
  }

  for (const t of modHelpers) {
    const w = wgslType(t);
    out.push(`fn pyre_mod_${t}(x: ${w}, y: ${w}) -> ${w} { return x - y * floor(x / y); }`);
  }
  return [...out, ...body, ''].join('\n');

  function block(stmts, depth) {
    const ind = '  '.repeat(depth);
    for (const s of stmts) {
      switch (s.kind) {
        case 'let':
        case 'var': {
          const init = s.init ? expr(s.init) : `${wgslType(s.type)}()`;
          body.push(`${ind}${s.kind} ${s.out}: ${wgslType(s.type)} = ${init};`);
          break;
        }
        case 'assign':
          body.push(`${ind}${expr(s.target)} ${s.op} ${expr(s.value)};`);
          break;
        case 'expr':
          body.push(`${ind}${expr(s.expr)};`);
          break;
        case 'if':
          s.branches.forEach((b, i) => {
            body.push(`${ind}${i ? '} else if' : 'if'} (${expr(b.cond)}) {`);
            block(b.body, depth + 1);
          });
          if (s.otherwise) { body.push(`${ind}} else {`); block(s.otherwise, depth + 1); }
          body.push(`${ind}}`);
          break;
        case 'for': {
          const cmp = s.stepValue > 0 ? '<' : '>';
          body.push(`${ind}for (var ${s.out}: i32 = ${expr(s.start)}; ${s.out} ${cmp} ${expr(s.end)}; ${s.out} += ${s.stepValue}) {`);
          block(s.body, depth + 1);
          body.push(`${ind}}`);
          break;
        }
        case 'while':
          body.push(`${ind}while (${expr(s.cond)}) {`);
          block(s.body, depth + 1);
          body.push(`${ind}}`);
          break;
        case 'return':
          body.push(`${ind}return${s.value ? ' ' + expr(s.value) : ''};`);
          break;
        case 'break':
        case 'continue':
          body.push(`${ind}${s.kind};`);
          break;
        default:
          break;
      }
    }
  }

  function construct(e) {
    const args = e.args.map(expr);
    if (isMat(e.ctor) && e.args.length === 1) {
      // WGSL has no diagonal-matrix constructor
      const n = dim(e.ctor);
      const cols = [];
      for (let c = 0; c < n; c++) {
        cols.push(`vec${n}<f32>(${Array.from({ length: n }, (_, r) => (r === c ? args[0] : '0.0')).join(', ')})`);
      }
      return `${wgslType(e.ctor)}(${cols.join(', ')})`;
    }
    return `${wgslType(e.ctor)}(${args.join(', ')})`;
  }

  function expr(e) {
    switch (e.kind) {
      case 'num': return e.isFloat ? fmtFloat(e.value) : String(e.value);
      case 'bool': return String(e.value);
      case 'ident':
        if (e.ref.kind === 'uniform') return `pyre_u.${e.ref.out}`;
        return e.ref.out;
      case 'unary': return e.op === 'not' ? `(!${expr(e.arg)})` : `(- ${expr(e.arg)})`;
      case 'binary': {
        const a = expr(e.left);
        const b = expr(e.right);
        if (e.op === '%' && e.type !== 'int') {
          modHelpers.add(e.type);
          return `pyre_mod_${e.type}(${a}, ${b})`;
        }
        if (e.op === '<<' || e.op === '>>') return `(${a} ${e.op} u32(${b} & 31))`;
        const op = e.op === 'and' ? '&&' : e.op === 'or' ? '||' : e.op;
        return `(${a} ${op} ${b})`;
      }
      case 'ternary': return `select(${expr(e.b)}, ${expr(e.a)}, ${expr(e.cond)})`;
      case 'member': return `${expr(e.object)}.${e.prop}`;
      case 'index':
        if (e.indexKind === 'buffer') return `${e.object.ref.out}[${expr(e.index)}]`;
        return `${expr(e.object)}[${expr(e.index)}]`;
      case 'ucall': return `${e.fn.out}(${e.args.map(expr).join(', ')})`;
      case 'bcall': {
        const args = e.args.map(expr);
        if (e.callee === 'mod') {
          if (e.generic === 'int') return `(${args[0]} % ${args[1]})`;
          modHelpers.add(e.type);
          return `pyre_mod_${e.type}(${args.join(', ')})`;
        }
        return `${BUILTIN_NAMES[e.callee] || e.callee}(${args.join(', ')})`;
      }
      case 'construct': return construct(e);
      default: return fail('cannot generate WGSL for this expression', e.pos);
    }
  }
}
